import { readFileSync } from "node:fs";
import { fileURLToPath, URL } from "node:url";

import { defineConfig, type Plugin } from "vite";

import {
  MODEL_BENCHMARK_PARITY_FILE,
  MODEL_BENCHMARK_SERVICE_WORKER,
  modelBenchmarkManifest,
} from "./tests/e2e/model-benchmark-manifest";

/**
 * Isolated, TEST-ONLY build for the candidate TMR benchmark.
 *
 * It emits `dist-model-benchmark/` — a self-contained MV3 extension whose only
 * page, `model-benchmark.html`, assembles the EXACT uncalibrated TMR inference
 * core and exposes a page-local scoring API. It reuses `public/` as the public
 * dir (so the verified `public/models/tmr-ai-text-detector/` bundle and the
 * offline `public/vendor/transformers-wasm/` assets travel along) and rewrites
 * the Transformers.js remote-host constants to `offline`, exactly like the
 * production build, so nothing reaches the network.
 *
 * The runtime-parity manifest is generated by the Phase 2 owner command
 * (`scripts/runtime-parity.mjs write`) into `benchmark/work/model-benchmark/`
 * BEFORE this build runs; the build embeds that exact object in the page (via the
 * `__CLEANFEED_RUNTIME_PARITY__` define) and emits the byte-identical JSON as
 * `runtime-parity.json`, so the scorer can bind embedded to emitted.
 *
 * This entrypoint is deliberately absent from `vite.config.ts`,
 * `manifest.config.ts` and the production `dist/`. It never ships.
 */

const BENCHMARK_ROOT = fileURLToPath(
  new URL("./src/model-benchmark", import.meta.url),
);
const BENCHMARK_OUT = fileURLToPath(
  new URL("./dist-model-benchmark", import.meta.url),
);
const BENCHMARK_HTML = fileURLToPath(
  new URL("./src/model-benchmark/model-benchmark.html", import.meta.url),
);
const PUBLIC_DIR = fileURLToPath(new URL("./public", import.meta.url));
const RUNTIME_PARITY_PATH = fileURLToPath(
  new URL(
    "./benchmark/work/model-benchmark/runtime-parity.json",
    import.meta.url,
  ),
);

/** Reads the parity manifest the owner command wrote, failing closed if absent. */
function readRuntimeParityText(): string {
  try {
    return readFileSync(RUNTIME_PARITY_PATH, "utf8");
  } catch {
    throw new Error(
      `runtime-parity manifest missing at ${RUNTIME_PARITY_PATH}; run ` +
        `\`node scripts/runtime-parity.mjs write --model-manifest ` +
        `models/tmr-ai-text-detector/cleanfeed-model.json --output-dir ` +
        `benchmark/work/model-benchmark\` first`,
    );
  }
}

const runtimeParityText = readRuntimeParityText();

/** Emits the test-only manifest, the id-resolution worker and the parity JSON. */
function emitModelBenchmarkExtension(): Plugin {
  return {
    name: "cleanfeed-model-benchmark-extension",
    generateBundle() {
      this.emitFile({
        type: "asset",
        fileName: "manifest.json",
        source: `${JSON.stringify(modelBenchmarkManifest, null, 2)}\n`,
      });
      this.emitFile({
        type: "asset",
        fileName: MODEL_BENCHMARK_SERVICE_WORKER,
        source:
          "// Test-only service worker: exists so the Playwright fixture can\n" +
          "// resolve the extension id. It does no work and reaches no network.\n" +
          "self.addEventListener('install', () => {});\n",
      });
      // Emit the byte-identical parity manifest that the page embeds.
      this.emitFile({
        type: "asset",
        fileName: MODEL_BENCHMARK_PARITY_FILE,
        source: runtimeParityText,
      });
    },
  };
}

/** Mirrors production: neutralize the remote-host constants Transformers.js ships. */
function offlineTransformersRuntime(): Plugin {
  return {
    name: "cleanfeed-offline-transformers-runtime",
    generateBundle(_options, bundle) {
      for (const output of Object.values(bundle) as {
        type: string;
        code?: string;
      }[]) {
        if (output.type !== "chunk" || output.code === undefined) continue;
        output.code = output.code
          .replaceAll("https://huggingface.co", "offline")
          .replaceAll("https://cdn.jsdelivr.net", "offline");
      }
    },
  };
}

export default defineConfig({
  base: "./",
  root: BENCHMARK_ROOT,
  publicDir: PUBLIC_DIR,
  assetsInclude: ["**/*.wasm"],
  define: {
    __CLEANFEED_RUNTIME_PARITY__: JSON.stringify(runtimeParityText),
  },
  plugins: [emitModelBenchmarkExtension(), offlineTransformersRuntime()],
  resolve: {
    alias: {
      "@": fileURLToPath(new URL("./src", import.meta.url)),
    },
  },
  build: {
    outDir: BENCHMARK_OUT,
    emptyOutDir: true,
    rollupOptions: {
      input: BENCHMARK_HTML,
    },
  },
});
